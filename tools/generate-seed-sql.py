#!/usr/bin/env python3
"""Regenerate supabase/seed.sql from the event seed file.

The resource records are reference data, not application state, so they live in
git as SQL and are applied with `supabase db push` (or psql). Run this only when
the seed file changes:

    python3 tools/generate-seed-sql.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SEED = ROOT / "composeApp/src/wasmJsMain/resources/seed/oc-resources.seed.json"
OUT = ROOT / "supabase/seed.sql"

COLUMNS = [
    "id", "name", "organization", "category", "tags", "description", "services",
    "eligibility", "population", "how_to_access", "referral_required", "phone",
    "address", "city", "hours", "languages", "cost", "website", "source_url",
    "source_quote", "verified_date", "confidence", "notes",
]
ARRAYS = {"tags", "services", "population", "languages"}


def lit(value, column):
    """A SQL literal. Nulls stay null: the source not saying is information."""
    if column in ARRAYS:
        items = value or []
        if not items:
            return "'{}'"
        inner = ",".join('"' + str(i).replace("\\", "\\\\").replace('"', '\\"') + '"' for i in items)
        return "'{" + inner.replace("'", "''") + "}'"
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "true" if value else "false"
    return "'" + str(value).replace("'", "''") + "'"


def main():
    records = json.loads(SEED.read_text())["resources"]
    lines = [
        "-- Generated by tools/generate-seed-sql.py. Do not edit by hand.",
        f"-- Source: {SEED.relative_to(ROOT)} ({len(records)} records)",
        "-- Resource facts come from this file only; nothing here is model-generated.",
        "",
        "insert into public.resources (" + ", ".join(COLUMNS) + ") values",
    ]
    rows = [
        "  (" + ", ".join(lit(r.get(c), c) for c in COLUMNS) + ")"
        for r in records
    ]
    lines.append(",\n".join(rows))
    updates = ", ".join(f"{c} = excluded.{c}" for c in COLUMNS if c != "id")
    lines.append(f"on conflict (id) do update set {updates};")
    lines.append("")
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)} ({len(records)} records, {OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
